    // Plain byte/codepoint comparison breaks on Ukrainian: Є/І/Ї (U+0404/0406/0407)
    // sit in the Cyrillic Supplement block, far below the main block where the
    // rest of the alphabet (У+0410 and up) lives — so a naive sort would shove
    // every "І..." country (Індія, Ірландія, Іспанія…) to the very top. Rank by
    // position in the real alphabet instead, ignoring the apostrophe used in
    // words like "В'єтнам".
    $ukrainianAlphabet = mb_str_split('АБВГҐДЕЄЖЗИІЇЙКЛМНОПРСТУФХЦЧШЩЬЮЯ');
    $letterRank = array_flip($ukrainianAlphabet);

    $rankOf = fn (string $char): int => $letterRank[$char] ?? (100 + mb_ord($char));

    // Compare letter-by-letter (not PHP's array <=>, which sorts by array
    // length first and would clump "Того" ahead of "Тайвань" purely because
    // it has fewer characters, ignoring the actual letters).
    $compareNames = function (string $a, string $b) use ($rankOf): int {
        $la = mb_str_split(mb_strtoupper(str_replace(["'", '’', '-'], '', $a)));
        $lb = mb_str_split(mb_strtoupper(str_replace(["'", '’', '-'], '', $b)));

        for ($i = 0, $len = min(count($la), count($lb)); $i < $len; $i++) {
            $diff = $rankOf($la[$i]) <=> $rankOf($lb[$i]);

            if ($diff !== 0) {
                return $diff;
            }
        }

        return count($la) <=> count($lb);
    };

